// Pack the gift card PDF's fixed parts (background.pdf + the four TTFs) into worker/giftCardAssets.ts as base64,
// so the Worker, the vitest tests and the Vite build all load them the same way (no binary module rules).
//   node apps/web/scripts/gift-card/bundle.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../../worker/giftCardAssets.ts");
const b64 = (p) => readFileSync(path.join(here, p)).toString("base64");

const parts = {
  BACKGROUND: "background.pdf",
  FREDOKA_BOLD: "fonts/Fredoka-Bold.ttf",
  NUNITO_REGULAR: "fonts/Nunito-Regular.ttf",
  NUNITO_BOLD: "fonts/Nunito-Bold.ttf",
  GOCHI_HAND: "fonts/GochiHand-Regular.ttf",
};

const lines = [
  "// GENERATED by scripts/gift-card/bundle.mjs: do not edit. The gift card PDF's fixed parts, base64.",
  "// background.pdf: scripts/gift-card/render_background.py. Fonts: Fredoka, Nunito and Gochi Hand (SIL Open Font",
  "// License 1.1, see scripts/gift-card/fonts/OFL-*.txt), latin + latin-ext, from @fontsource (build_fonts.py).",
  "",
  ...Object.entries(parts).map(([name, file]) => `export const ${name} = "${b64(file)}";`),
  "",
];
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${path.relative(process.cwd(), out)} (${readFileSync(out).length} bytes)`);
